
CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    price_multiplier NUMERIC(5, 2) NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_of_birth DATE,
    email VARCHAR(255) NOT NULL UNIQUE,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL UNIQUE,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE car (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR(255) NOT NULL,
    latitude NUMERIC(38, 2) NOT NULL,
    longitude NUMERIC(38, 2) NOT NULL,
    model VARCHAR(255) NOT NULL,
    price_per_day NUMERIC(38, 2) NOT NULL,
    year INTEGER NOT NULL,
    category_id BIGINT REFERENCES category(id),
    image_url VARCHAR(255)
);

CREATE TABLE rental (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    end_time TIMESTAMP,
    planned_end_time TIMESTAMP NOT NULL,
    price_per_day NUMERIC(38, 2) NOT NULL,
    start_time TIMESTAMP NOT NULL,
    status VARCHAR(255) NOT NULL
        CHECK (status IN ('PENDING', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    total_price NUMERIC(38, 2) NOT NULL,
    car_id BIGINT REFERENCES car(id),
    user_id BIGINT REFERENCES users(id)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2) NOT NULL,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    payment_method VARCHAR(255) NOT NULL
        CHECK (payment_method IN ('CREDIT_CARD', 'DEBIT_CARD', 'CASH')),
    status VARCHAR(255) NOT NULL
        CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED', 'REFUNDED')),
    rental_id BIGINT NOT NULL REFERENCES rental(id)
);
